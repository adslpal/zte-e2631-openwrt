#!/bin/sh
# =============================================================================
# apply-h60g.sh -- add an H60G board to a tree that ALREADY has the E2631
# overlay applied (Zlion-Y/zte-e2631-openwrt).
#
# Why build on top of E2631 instead of the bare base tree:
#   The SoC drivers (gmac/switch/PPE/MDIO/SPI-NAND), the 6.18 kernel patches,
#   the soft-float config and the build chain are all E2631-port work and are
#   IDENTICAL for H60G (same ZX279128S silicon). We only swap the board layer.
#
# Usage:
#   1) Prepare the E2631 tree first (its own README/BUILD.md):
#        git clone --branch pr-zte-zxhn-h3600 <base> openwrt
#        cd zte-e2631-openwrt && ./apply.sh ../openwrt
#   2) Fill every TODO(H60G) in dts/zx279128s-zte-h60g.dts from probe output.
#   3) Run:  ./apply-h60g.sh ../openwrt
#   4) Build: make -C ../openwrt menuconfig   (select Target Device: zte_h60g)
#             make -C ../openwrt -j$(nproc)
#
# Idempotent. Paths are all relative to the tree root passed as $1.
# =============================================================================
set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
TREE=${1:-../openwrt}

[ -d "$TREE/target/linux/sanechips" ] || {
	echo "apply-h60g.sh: no sanechips target in $TREE" >&2; exit 1; }
# Require the E2631 port to be present -- that is where the shared drivers live.
[ -f "$TREE/target/linux/sanechips/dts/zx279128s-zte-zxhn-e2631.dts" ] || {
	echo "apply-h60g.sh: E2631 overlay not applied in $TREE." >&2
	echo "        Run zte-e2631-openwrt/apply.sh first." >&2; exit 1; }

# Guard against shipping an unfilled template.
if grep -q 'TODO(H60G) #1b' "$HERE/dts/zx279128s-zte-h60g.dts" && \
   grep -q '0x01700000 0x02800000' "$HERE/dts/zx279128s-zte-h60g.dts"; then
	echo "WARNING: dts rootfs partition still at placeholder 0x1700000/0x2800000." >&2
	echo "         Fill from probe output before flashing. Continuing for a test build only." >&2
fi

# --- 1. board DTS -----------------------------------------------------------
mkdir -p "$TREE/target/linux/sanechips/dts"
cp "$HERE/dts/zx279128s-zte-h60g.dts" "$TREE/target/linux/sanechips/dts/"

# The base tree's dts Makefile is generated by the patches; register the new
# dtb there. Image build uses DEVICE_DTS so the Makefile entry is informational,
# but keep it consistent for `make dtbs`.
DTSMK="$TREE/target/linux/sanechips/dts/Makefile"
if [ -f "$DTSMK" ] && ! grep -q 'zx279128s-zte-h60g' "$DTSMK"; then
	printf 'dtb-$(CONFIG_SOC_ZX279128S) += zx279128s-zte-h60g.dtb\n' >> "$DTSMK"
fi

# --- 2. image Device definition --------------------------------------------
IMG="$TREE/target/linux/sanechips/image/Makefile"
cp "$HERE/target/image/Makefile.h60g" "$TREE/target/linux/sanechips/image/"
if ! grep -q 'Makefile.h60g' "$IMG"; then
	# hook our include right after the E2631 include, before BuildImage
	if grep -q 'Makefile.e2631' "$IMG"; then
		sed -i 's|^\(include $(TOPDIR)/target/linux/sanechips/image/Makefile.e2631\)$|\1\ninclude $(TOPDIR)/target/linux/sanechips/image/Makefile.h60g|' "$IMG"
	else
		sed -i 's|^$(eval $(call BuildImage))$|include $(TOPDIR)/target/linux/sanechips/image/Makefile.h60g\n\n$(eval $(call BuildImage))|' "$IMG"
	fi
fi
grep -q 'Makefile.h60g' "$IMG" || { echo "failed to hook image/Makefile" >&2; exit 1; }

# --- 3. network map ---------------------------------------------------------
cp "$HERE/target/base-files/etc/board.d/02_network" \
   "$TREE/target/linux/sanechips/base-files/etc/board.d/02_network"

# --- 4. kernel cmdline ------------------------------------------------------
# REV2 (2026-11-27): H60G has a 256MiB PARALLEL NAND (denali), which mainline
# 6.18 has NO driver for. The stock Flash is invisible to the kernel, and the
# DTS partition block is disabled (#if 0). Therefore DO NOT force a
# `root=/dev/mtdblockN` here -- there is no valid root device until the
# parallel-NAND driver is ported. Use a console-only cmdline; the first boot is
# an initramfs loaded over TFTP (root comes from the initramfs itself).
CFG="$TREE/target/linux/sanechips/config-6.18"
MARK='# H60G: rev6 -- earlyprintk (DEBUG_LL/pl01x) + ATAGS->DTB compat (EXTEND) + earlycon (apply-h60g.sh)'
# ---------------------------------------------------------------------------
# REV4 (2026-11-27) -- why the kernel was TOTALLY silent after "Starting kernel"
#
# U-Boot on this box is ZTE-customised and passes legacy ATAGS in r2, not a
# DTB. With CONFIG_ARM_ATAG_DTB_COMPAT=n the appended DTB is only a fallback
# and, because a "valid" ATAGS pointer is present, the kernel ends up with
# ATAGS. A multiplatform DT-only kernel then has no machine_desc, no
# /chosen/stdout-path and no earlycon target => it dies before any console
# exists, which is indistinguishable from a hang.
#
# Three independent fixes, so that ONE boot tells us exactly where we are:
#   1. ARM_ATAG_DTB_COMPAT  - merge the U-Boot ATAGS into the appended DTB,
#                             so the DTB we ship is always the one used.
#                             (REV5: its CMDLINE_EXTEND sub-choice MUST be
#                             pinned or syncconfig fails -- see below.)
#   2. earlycon=pl011,0x94404000
#                           - bare "earlycon" needs DT stdout-path; the
#                             explicit MMIO form works with no DTB at all.
#                             UART is serial@94404000 (arm,pl011).
#   3. (removed in REV5) DEBUG_LL/DEBUG_UNCOMPRESS
#                           - impossible here: DEBUG_UNCOMPRESS depends on
#                             !ARCH_MULTIPLATFORM and this target IS
#                             multiplatform. Use the raw-Image test instead
#                             (boot-test2.py --image raw) to tell "decompressor
#                             broken" from "kernel dies early".
# ---------------------------------------------------------------------------
sed -i -e "\|^$MARK\$|d" \
       -e '/^CONFIG_CMDLINE=/d' \
       -e '/^CONFIG_CMDLINE_BOOL=/d' \
       -e '/^CONFIG_CMDLINE_FORCE=/d' \
       -e '/^CONFIG_SERIAL_EARLYCON=/d' \
       -e '/^CONFIG_SERIAL_AMBA_PL011_EARLYCON=/d' \
       -e '/^CONFIG_ARM_ATAG_DTB_COMPAT=/d' \
       -e '/^CONFIG_ARM_ATAG_DTB_COMPAT_CMDLINE_/d' \
       -e '/^CONFIG_EARLY_PRINTK=/d' \
       -e '/^CONFIG_DEBUG_KERNEL=/d' \
       -e '/^CONFIG_DEBUG_LL=/d' \
       -e '/^CONFIG_DEBUG_LL_UART_PL01X=/d' \
       -e '/^CONFIG_DEBUG_UART_PHYS=/d' \
       -e '/^CONFIG_DEBUG_UART_VIRT=/d' \
       "$CFG"
# NOTE (REV5): CONFIG_DEBUG_UNCOMPRESS can never be enabled here --
#   arch/arm/Kconfig.debug: "config DEBUG_UNCOMPRESS depends on
#   !ARCH_MULTIPLATFORM", and this target is CONFIG_ARCH_MULTIPLATFORM=y
#   (sanechips/config-6.18 line 6). The decompressor stays silent by design.
#
# NOTE (REV6): earlyprintk IS possible and is the only channel that can print
#   before earlycon exists. Two traps:
#     * DEBUG_LL needs DEBUG_KERNEL=y, otherwise it is silently dropped.
#     * the user-visible choice entry is DEBUG_LL_UART_PL01X; DEBUG_UART_PL01X
#       is only the hidden symbol that it selects. Writing the hidden name does
#       nothing.
#   With earlyprintk, text appears from the very first printk in start_kernel,
#   and head.S error paths ("Error: unrecognized/unsupported machine ID") also
#   print -- exactly what we need if the kernel dies before console_init.
#
# NOTE (REV5): ARM_ATAG_DTB_COMPAT opens a NEW choice
#   ARM_ATAG_DTB_COMPAT_CMDLINE_{FROM_BOOTLOADER,EXTEND}. If neither is pinned,
#   the non-interactive `syncconfig` step stops at "choice[1-2?]:" and the whole
#   target/linux build dies with Error 1. It must always be set explicitly.
printf '%s\n' "$MARK" \
	'CONFIG_CMDLINE_BOOL=y' \
	'CONFIG_CMDLINE="console=ttyAMA0,115200n8 earlycon=pl011,0x94404000 earlyprintk keep_bootcon"' \
	'CONFIG_CMDLINE_FORCE=y' \
	'CONFIG_SERIAL_EARLYCON=y' \
	'CONFIG_SERIAL_AMBA_PL011_EARLYCON=y' \
	'CONFIG_ARM_ATAG_DTB_COMPAT=y' \
	'CONFIG_ARM_ATAG_DTB_COMPAT_CMDLINE_EXTEND=y' \
	'CONFIG_DEBUG_KERNEL=y' \
	'CONFIG_DEBUG_LL=y' \
	'CONFIG_DEBUG_LL_UART_PL01X=y' \
	'CONFIG_DEBUG_UART_PHYS=0x94404000' \
	'CONFIG_DEBUG_UART_VIRT=0xfee04000' \
	'CONFIG_EARLY_PRINTK=y' >> "$CFG"
echo "cmdline: console + earlycon=pl011,0x94404000 + earlyprintk (DEBUG_LL/pl01x)"
echo "kernel is zImage+appended-DTB, ih_load=0x48008000 (AUTO_ZRELADDR unpacks there)"

# --- 5. select only the H60G profile in seed config -------------------------
# Leave E2631 default intact; user selects zte_h60g in menuconfig. We only make
# sure the WiFi kmods pulled by E2631's DEVICE_PACKAGES don't leak in -- our
# Makefile.h60g has its own DEVICE_PACKAGES without them.
echo
echo "apply-h60g.sh: done."
echo "Next:"
echo "  make -C $TREE menuconfig   # Target System: Sanechips, Profile: ZTE H60G"
echo "  make -C $TREE -j\$(nproc)"
echo "Then fill TODO(H60G) fields and re-run this script + rebuild before flashing."
